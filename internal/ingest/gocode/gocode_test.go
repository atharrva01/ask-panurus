const driverSrc = `//go:build evm

package evm

import (
	"context"
	"errors"
)

// Driver creates EVM networks.
type Driver struct {
	name string
}

type (
	// Option configures a Driver.
	Option func(*Driver)
	id     string
)

const (
	A = 1
	B = 2
)

func init() {}

func init() {}

// New returns a network.
func (d *Driver) New(ctx context.Context) error {
	return errors.New(d.name)
}
`

const otherFileSrc = `package evm

func (d Driver) Name() string { return d.name }
`

func chunkByKey(t *testing.T, cs []chunk.Chunk) map[string]chunk.Chunk {
	t.Helper()
	chunk.AssignIDs(cs)
	m := make(map[string]chunk.Chunk)
	for _, c := range cs {
		if _, dup := m[c.ID]; dup {
			t.Fatalf("duplicate id %s", c.ID)
		}
		m[c.ID] = c
	}
	return m
}

func TestChunkDir(t *testing.T) {
	res := ChunkDir("example.com/x/evm", []File{
		{Path: "x/evm/driver.go", Src: []byte(driverSrc)},
		{Path: "x/evm/name.go", Src: []byte(otherFileSrc)},
	}, false)
	if len(res.Errors) > 0 {
		t.Fatal(res.Errors)
	}
	m := chunkByKey(t, res.Chunks)

	newFn, ok := m["code:x/evm/driver.go:Driver.New#0"]
	if !ok {
		t.Fatalf("method chunk missing; have %v", keys(m))
	}
	if newFn.Receiver != "*Driver" || newFn.Symbol != "New" {
		t.Errorf("receiver/symbol = %q/%q", newFn.Receiver, newFn.Symbol)
	}
	if newFn.StartLine != 30 || newFn.EndLine != 33 {
		t.Errorf("lines = %d-%d, want 30-33 (doc comment included)", newFn.StartLine, newFn.EndLine)
	}
	if !strings.HasPrefix(newFn.Content, "// New returns a network.\nfunc (d *Driver) New") {
		t.Errorf("content = %q", newFn.Content)
	}
	if newFn.BuildTags != "evm" {
		t.Errorf("build tags = %q", newFn.BuildTags)
	}
	if newFn.DocComment != "New returns a network." {
		t.Errorf("doc = %q", newFn.DocComment)
	}
	if !strings.Contains(newFn.EmbedText, "// package example.com/x/evm\n") {
		t.Errorf("embed header missing: %q", newFn.EmbedText)
	}

	// Two init functions in one file must get distinct IDs.
	if _, ok := m["code:x/evm/driver.go:init#1"]; !ok {
		t.Errorf("second init missing; have %v", keys(m))
	}

	// The type chunk lists methods declared in other files of the package.
	drv := m["code:x/evm/driver.go:Driver#0"]
	if !strings.Contains(drv.EmbedText, "// methods: Name, New") {
		t.Errorf("type embed text = %q", drv.EmbedText)
	}
	if strings.Contains(drv.Content, "methods:") {
		t.Error("method list leaked into displayed content")
	}

	// Grouped type specs become separate chunks with their own doc.
	opt := m["code:x/evm/driver.go:Option#0"]
	if opt.DocComment != "Option configures a Driver." || opt.StartLine != 16 {
		t.Errorf("grouped spec = %+v", opt)
	}

	if _, ok := m["code:x/evm/driver.go:const A, B#0"]; !ok {
		t.Errorf("const block missing; have %v", keys(m))
	}
}

func TestSkipsGeneratedAndTests(t *testing.T) {
	gen := "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage v1\n\ntype X struct{}\n"
	tst := "package v1\n\nfunc TestX() {}\n"
	files := []File{{Path: "p/x.pb.go", Src: []byte(gen)}, {Path: "p/x_test.go", Src: []byte(tst)}}

	res := ChunkDir("p", files, false)
	if len(res.Chunks) != 0 || len(res.Generated) != 1 {
		t.Fatalf("chunks=%d generated=%v", len(res.Chunks), res.Generated)
	}
	res = ChunkDir("p", files, true)
	if len(res.Chunks) != 1 || res.Chunks[0].Kind != chunk.KindTest {
		t.Fatalf("with tests: %+v", res.Chunks)
	}
}

func TestLongFunctionSplitsContiguously(t *testing.T) {
	var b strings.Builder
	b.WriteString("package p\n\n// Big does a lot.\nfunc Big() {\n")
	for i := 0; i < 400; i++ {
		fmt.Fprintf(&b, "\t_ = %d\n", i)
	}
	b.WriteString("}\n")

	res := ChunkDir("p", []File{{Path: "p/big.go", Src: []byte(b.String())}}, false)
	cs := res.Chunks
	if len(cs) < 3 {
		t.Fatalf("got %d parts, want >= 3", len(cs))
	}
	if cs[0].StartLine != 3 || cs[len(cs)-1].EndLine != 405 {
		t.Errorf("parts span %d-%d, want 3-405", cs[0].StartLine, cs[len(cs)-1].EndLine)
	}
	for i := 1; i < len(cs); i++ {
		if cs[i].StartLine != cs[i-1].EndLine+1 {
			t.Errorf("gap between part %d and %d", i-1, i)
		}
		if !strings.Contains(cs[i].EmbedText, "func Big()") {
			t.Errorf("part %d embed text lacks signature", i)
		}
	}
	chunkByKey(t, cs)
}

func TestParseErrorIsReportedNotFatal(t *testing.T) {
	res := ChunkDir("p", []File{
		{Path: "p/bad.go", Src: []byte("package p\nfunc {")},
		{Path: "p/ok.go", Src: []byte("package p\nfunc OK() {}\n")},
	}, false)
	if len(res.Errors) != 1 || len(res.Chunks) != 1 {
		t.Fatalf("errors=%v chunks=%d", res.Errors, len(res.Chunks))
	}
}

func keys(m map[string]chunk.Chunk) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	return out
}
